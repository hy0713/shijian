def main():
    docs = json.loads(Path("data/demo/corpus.json").read_text("utf-8"))
    questions = []
    for i, (category, question, refs, rubric) in enumerate(SPECS, 1):
        expected = []
        for doc_id, quote in refs:
            doc = docs[doc_id]
            if quote not in doc["raw_text"]:
                raise ValueError(f"Q{i}: evidence anchor not found: {quote}")
            expected.append({"title": doc["title"], "chapter": doc["chapter"], "quote": quote})
        questions.append(
            {
                "id": f"Q{i:02}",
                "category": category,
                "question": question,
                "expected_evidence": expected,
                "human_rubric": rubric,
                "gold_status": "seed_rubric_requires_human_review",
            }
        )
    Path("eval").mkdir(exist_ok=True)
    Path("eval/questions.json").write_text(json.dumps(questions, ensure_ascii=False, indent=2), "utf-8")
    print(f"Validated {len(questions)} question rubrics and all evidence anchors")


if __name__ == "__main__":
    main()
